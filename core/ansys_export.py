"""
ANSYS Mechanical APDL export and result import.

Two input files are generated so the in-app solver can be checked in ANSYS [17]:

A) <name>_same_mesh.inp  -- CODE VERIFICATION
   The exact nodes/elements of this app's mesh are written with N and E commands
   (PLANE55, triangles as degenerate quads). Same discretisation, same materials,
   same converged h values and heat loads. ANSYS and this app should agree to
   round-off; any difference points to a formulation bug on one side.

B) <name>_ansys_mesh.inp -- SOLUTION VERIFICATION
   The geometry is rebuilt from primitives (CYL4 / RECTNG + Booleans) and meshed by
   ANSYS with 8-node PLANE77 elements. Different element order and mesher, so the
   peak temperature should agree within the discretisation error (GCI) of both.

Cell orthotropy: each cell gets a local cylindrical coordinate system (LOCAL,kcn,1)
and its elements use ESYS = kcn, so material X = radial (KXX = k_r) and
material Y = tangential (KYY = k_t), evaluated at each element centroid.

Both scripts write ansys_nodal_T.csv (node, x, y, T) that can be uploaded back
into the app for a point-by-point comparison.
"""
from __future__ import annotations

import io
import numpy as np

from .mesh import Mesh, PackGeometry, REG_CASING, REG_FILLER, REG_CELL0

KCN0 = 100   # first local coordinate system number used for cells


def _hdr(title: str) -> str:
    return (f"! {title}\n"
            "! Generated by the Ather 450X battery thermal FEA app.\n"
            "! Units: SI (m, W, K-or-C, s). Plane analysis, results per unit depth.\n"
            "FINISH\n/CLEAR,NOSTART\n"
            f"/TITLE,{title[:70]}\n")


def _materials(mat: dict) -> str:
    s = io.StringIO()
    s.write("! ---- materials: 1 = cell (orthotropic in cell cylindrical CS), 2 = filler, 3 = casing\n")
    s.write(f"MP,KXX,1,{mat['k_r']:.6g}\nMP,KYY,1,{mat['k_t']:.6g}\n")
    s.write(f"MP,DENS,1,{mat['rho_cell']:.6g}\nMP,C,1,{mat['cp_cell']:.6g}\n")
    s.write(f"MP,KXX,2,{mat['k_fill']:.6g}\nMP,DENS,2,{mat['rho_fill']:.6g}\nMP,C,2,{mat['cp_fill']:.6g}\n")
    s.write(f"MP,KXX,3,{mat['k_case']:.6g}\nMP,DENS,3,{mat['rho_case']:.6g}\nMP,C,3,{mat['cp_case']:.6g}\n")
    return s.getvalue()


def _local_cs(centres: np.ndarray) -> str:
    s = io.StringIO()
    s.write("! ---- one local cylindrical CS per cell (x = radial, y = tangential)\n")
    for i, (x, y) in enumerate(centres):
        s.write(f"LOCAL,{KCN0 + i},1,{x:.9e},{y:.9e},0\n")
    s.write("CSYS,0\n")
    return s.getvalue()


def _results_block(fname: str = "ansys_nodal_T") -> str:
    return f"""
! ---- post-processing
/POST1
SET,LAST
NSEL,ALL
NSORT,TEMP
*GET,TMAX_ANSYS,SORT,0,MAX
*GET,TMIN_ANSYS,SORT,0,MIN
NUSORT
*GET,NMAXD,NODE,0,NUM,MAXD
*DEL,ND_ID,,NOPR
*DEL,ND_X,,NOPR
*DEL,ND_Y,,NOPR
*DEL,ND_T,,NOPR
*DEL,ND_S,,NOPR
*DIM,ND_ID,ARRAY,NMAXD
*DIM,ND_X,ARRAY,NMAXD
*DIM,ND_Y,ARRAY,NMAXD
*DIM,ND_T,ARRAY,NMAXD
*DIM,ND_S,ARRAY,NMAXD
*VFILL,ND_ID(1),RAMP,1,1
*VGET,ND_S(1),NODE,1,NSEL
*VGET,ND_X(1),NODE,1,LOC,X
*VGET,ND_Y(1),NODE,1,LOC,Y
*VGET,ND_T(1),NODE,1,TEMP
*CFOPEN,{fname},csv
*VWRITE,ND_ID(1),ND_X(1),ND_Y(1),ND_T(1),ND_S(1)
(F10.0,',',E18.10,',',E18.10,',',E18.10,',',F4.0)
*CFCLOS
*MSG,UI,TMAX_ANSYS,TMIN_ANSYS
Peak temperature %G C, minimum %G C. Nodal results written to {fname}.csv
PLNSOL,TEMP
"""


def _bc_lines_nodes(side: str, W: float, H: float, d: dict, bc_kind: str, T_fix: float, T_inf: float) -> str:
    tol = 1e-7
    sel = {"bottom": f"NSEL,S,LOC,Y,{-tol:.3e},{tol:.3e}",
           "top": f"NSEL,S,LOC,Y,{H - tol:.9e},{H + tol:.9e}",
           "left": f"NSEL,S,LOC,X,{-tol:.3e},{tol:.3e}",
           "right": f"NSEL,S,LOC,X,{W - tol:.9e},{W + tol:.9e}"}[side]
    if bc_kind == "fixed":
        return f"{sel}\nD,ALL,TEMP,{T_fix:.6g}\n"
    if d["h"] > 0:
        return f"{sel}\nSF,ALL,CONV,{d['h']:.8g},{T_inf:.6g}\n"
    return f"! {side}: insulated (natural boundary condition, nothing to apply)\n"


def same_mesh_apdl(mesh: Mesh, mat: dict, hs: dict, side_kinds: dict, side_Tfix: dict,
                   q_cell: np.ndarray, T_inf: float, title="Ather450X_pack_same_mesh") -> str:
    """Write the app's own mesh to APDL (PLANE55)."""
    s = io.StringIO()
    s.write(_hdr(title))
    s.write("/PREP7\nET,1,PLANE55\n")
    s.write(_materials(mat))
    s.write(_local_cs(mesh.centres))
    s.write("! ---- nodes\n")
    for i, (x, y) in enumerate(mesh.p, 1):
        s.write(f"N,{i},{x:.12e},{y:.12e}\n")
    s.write("! ---- elements (triangles as degenerate PLANE55 quads: I,J,K,K)\n")
    s.write("TYPE,1\n")
    order = np.lexsort((mesh.region,))
    # write casing, filler, then cell by cell so cell element ranges are contiguous
    eid = 0
    ranges = {}
    for reg in sorted(set(mesh.region.tolist())):
        idx = np.where(mesh.region == reg)[0]
        if reg == REG_CASING:
            s.write("MAT,3\nESYS,0\n")
        elif reg == REG_FILLER:
            s.write("MAT,2\nESYS,0\n")
        else:
            s.write(f"MAT,1\nESYS,{KCN0 + reg - REG_CELL0}\n")
        start = eid + 1
        for e in idx:
            a, b, c = mesh.t[e] + 1
            eid += 1
            s.write(f"E,{a},{b},{c},{c}\n")
        ranges[reg] = (start, eid)
    s.write("ESYS,0\nALLSEL\n")
    s.write("! ---- heat generation per cell (W/m3)\n")
    for reg, (a, b) in ranges.items():
        if reg >= REG_CELL0:
            s.write(f"ESEL,S,ELEM,,{a},{b}\nBFE,ALL,HGEN,1,{q_cell[reg - REG_CELL0]:.8g}\n")
    s.write("ALLSEL\n! ---- boundary conditions (converged h values from the app: convection + radiation)\n")
    for side in ("bottom", "top", "left", "right"):
        s.write(_bc_lines_nodes(side, mesh.W, mesh.H, hs[side], side_kinds[side], side_Tfix.get(side, 0.0), T_inf))
    s.write("ALLSEL\nFINISH\n/SOLU\nANTYPE,STATIC\nSOLVE\nFINISH\n")
    s.write(_results_block("ansys_nodal_T_same_mesh"))
    return s.getvalue()


def geometry_apdl(g: PackGeometry, mat: dict, hs: dict, side_kinds: dict, side_Tfix: dict,
                  q_cell: np.ndarray, T_inf: float, esize: float,
                  title="Ather450X_pack_ansys_mesh") -> str:
    """Rebuild the geometry from primitives and let ANSYS mesh it (PLANE77)."""
    C = g.centres()
    r = 0.5 * g.cell_d
    W, H, t = g.W, g.H, g.wall
    N = len(C)
    s = io.StringIO()
    s.write(_hdr(title))
    s.write("/PREP7\nET,1,PLANE77\n")
    s.write(_materials(mat))
    s.write(_local_cs(C))
    s.write("CSYS,0\n! ---- cells: areas 1..N\n")
    for (x, y) in C:
        s.write(f"CYL4,{x:.9e},{y:.9e},{r:.9e}\n")
    s.write("! ---- filler = inner rectangle minus cells (cells kept)\n")
    s.write(f"RECTNG,{t:.9e},{W - t:.9e},{t:.9e},{H - t:.9e}\n")
    s.write(f"ASEL,ALL\nASBA,{N + 1},ALL,,DELETE,KEEP\nALLSEL\n")
    s.write("! ---- casing as four strips (top/bottom span the full width)\n")
    s.write(f"RECTNG,0,{W:.9e},0,{t:.9e}\n")
    s.write(f"RECTNG,0,{W:.9e},{H - t:.9e},{H:.9e}\n")
    s.write(f"RECTNG,0,{t:.9e},{t:.9e},{H - t:.9e}\n")
    s.write(f"RECTNG,{W - t:.9e},{W:.9e},{t:.9e},{H - t:.9e}\n")
    s.write("ALLSEL\nAGLUE,ALL\nNUMCMP,AREA\nALLSEL\n")
    tol = 1e-6
    s.write("! ---- identify regions by area-centroid location (robust to renumbering)\n")
    s.write(f"ASEL,S,LOC,Y,-1,{t:.9e}\nASEL,A,LOC,Y,{H - t:.9e},{H + 1:.6g}\n")
    s.write(f"ASEL,A,LOC,X,-1,{t:.9e}\nASEL,A,LOC,X,{W - t:.9e},{W + 1:.6g}\nCM,CASE,AREA\n")
    s.write("AATT,3,,1,0\n")
    # filler: areas attached to the inner bottom line, minus the bottom casing strip
    s.write(f"LSEL,S,LOC,Y,{t - tol:.9e},{t + tol:.9e}\nLSEL,R,LOC,X,{t + tol:.9e},{W - t - tol:.9e}\n")
    s.write("ASLL,S\nCMSEL,U,CASE\nCM,FILL,AREA\nAATT,2,,1,0\n")
    for i, (x, y) in enumerate(C):
        s.write(f"ASEL,S,LOC,X,{x - tol:.9e},{x + tol:.9e}\nASEL,R,LOC,Y,{y - tol:.9e},{y + tol:.9e}\n"
                f"CMSEL,U,FILL\nCMSEL,U,CASE\nCM,CELL{i + 1},AREA\nAATT,1,,1,{KCN0 + i}\n")
    s.write(f"ALLSEL\nESIZE,{esize:.6e}\nMSHKEY,0\nMSHAPE,0,2D\nAMESH,ALL\n")
    s.write("! ---- heat generation per cell (W/m3)\n")
    for i in range(N):
        s.write(f"CMSEL,S,CELL{i + 1}\nESLA,S\nBFE,ALL,HGEN,1,{q_cell[i]:.8g}\n")
    s.write("ALLSEL\n! ---- boundary conditions on outer lines\n")
    linesel = {"bottom": f"LSEL,S,LOC,Y,{-tol:.3e},{tol:.3e}",
               "top": f"LSEL,S,LOC,Y,{H - tol:.9e},{H + tol:.9e}",
               "left": f"LSEL,S,LOC,X,{-tol:.3e},{tol:.3e}",
               "right": f"LSEL,S,LOC,X,{W - tol:.9e},{W + tol:.9e}"}
    for side in ("bottom", "top", "left", "right"):
        kind = side_kinds[side]
        if kind == "fixed":
            s.write(f"{linesel[side]}\nDL,ALL,,TEMP,{side_Tfix.get(side, 0.0):.6g}\n")
        elif hs[side]["h"] > 0:
            s.write(f"{linesel[side]}\nSFL,ALL,CONV,{hs[side]['h']:.8g},,{T_inf:.6g}\n")
        else:
            s.write(f"! {side}: insulated\n")
    s.write("ALLSEL\nSFTRAN\nDTRAN\nFINISH\n/SOLU\nANTYPE,STATIC\nSOLVE\nFINISH\n")
    s.write(_results_block("ansys_nodal_T_ansys_mesh"))
    return s.getvalue()


def geometry_dxf(g: PackGeometry) -> str:
    """Minimal DXF (R12, mm) of the section for import into SpaceClaim / DesignModeler."""
    C = g.centres() * 1e3
    r = 0.5 * g.cell_d * 1e3
    W, H, t = g.W * 1e3, g.H * 1e3, g.wall * 1e3
    out = ["0", "SECTION", "2", "ENTITIES"]

    def line(x1, y1, x2, y2, layer):
        out.extend(["0", "LINE", "8", layer, "10", f"{x1:.6f}", "20", f"{y1:.6f}", "30", "0",
                    "11", f"{x2:.6f}", "21", f"{y2:.6f}", "31", "0"])

    def rect(x0, y0, x1, y1, layer):
        line(x0, y0, x1, y0, layer); line(x1, y0, x1, y1, layer)
        line(x1, y1, x0, y1, layer); line(x0, y1, x0, y0, layer)

    rect(0, 0, W, H, "CASING_OUTER")
    rect(t, t, W - t, H - t, "CASING_INNER")
    for x, y in C:
        out.extend(["0", "CIRCLE", "8", "CELLS", "10", f"{x:.6f}", "20", f"{y:.6f}", "30", "0", "40", f"{r:.6f}"])
    out.extend(["0", "ENDSEC", "0", "EOF"])
    return "\n".join(out) + "\n"


def parse_ansys_csv(text: str) -> np.ndarray:
    """Parse node,x,y,T[,selected] rows written by the APDL scripts. Returns (n,3) x,y,T."""
    rows = []
    for ln in text.splitlines():
        parts = [p.strip() for p in ln.split(",")]
        if len(parts) < 4:
            continue
        try:
            vals = [float(p) for p in parts[:5]]
        except ValueError:
            continue
        if len(vals) == 5 and vals[4] <= 0:     # node not selected / does not exist
            continue
        rows.append(vals[1:4])
    return np.array(rows)
